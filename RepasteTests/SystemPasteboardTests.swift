import XCTest
import AppKit
import RepasteCore

final class SystemPasteboardTests: XCTestCase {
    private var pasteboard: NSPasteboard!

    override func setUp() {
        super.setUp()
        // Uniquely-named pasteboard: doesn't touch the user's general clipboard.
        pasteboard = NSPasteboard(name: NSPasteboard.Name("RepasteTest-\(UUID().uuidString)"))
    }

    override func tearDown() {
        pasteboard.releaseGlobally()
        pasteboard = nil
        super.tearDown()
    }

    private func putString(_ s: String, marker: String? = nil) {
        pasteboard.clearContents()
        pasteboard.setString(s, forType: .string)
        if let marker { pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType(marker)) }
    }

    // MARK: - Privacy: protected content isn't read

    func testConcealedContentIsProtectedAndNotRead() {
        putString("s3cr3t", marker: "org.nspasteboard.ConcealedType")
        let content = SystemPasteboard(pasteboard: pasteboard).read()
        XCTAssertTrue(content.isProtected)
        XCTAssertNil(content.text)                 // protected text is never read
    }

    func testTransientAndOnePasswordMarkersAreProtected() {
        for marker in ["org.nspasteboard.TransientType", "com.agilebits.onepassword"] {
            putString("x", marker: marker)
            let content = SystemPasteboard(pasteboard: pasteboard).read()
            XCTAssertTrue(content.isProtected, "\(marker) must mark as protected")
            XCTAssertNil(content.text)
        }
    }

    // MARK: - Normal read / write

    func testPlainTextIsReadAndNotProtected() {
        putString("hello world")
        let content = SystemPasteboard(pasteboard: pasteboard).read()
        XCTAssertFalse(content.isProtected)
        XCTAssertEqual(content.text, "hello world")
    }

    func testWriteSetsStringAndSourceWithoutTransientMarkers() {
        SystemPasteboard(pasteboard: pasteboard).write("clean", source: "com.calo.RePaste")

        XCTAssertEqual(pasteboard.string(forType: .string), "clean")
        XCTAssertEqual(pasteboard.string(forType: NSPasteboard.PasteboardType("org.nspasteboard.source")),
                       "com.calo.RePaste")
        let markers = (pasteboard.types ?? []).map(\.rawValue)
        XCTAssertFalse(markers.contains { $0.contains("Transient") || $0.contains("Concealed")
                                          || $0.contains("AutoGenerated") })
    }
}
